// Keep pre-release products out of navigation and discovery.
export const visibleApps = apps.filter((app) => app.slug !== 'marta-easy');

export const appPages = [
  ...apps.map((app) => ({
    ...app,
    route: `/${app.slug}/`,
    hidden: !visibleApps.includes(app),
    hasPolicies: true,
  })),
  {
    slug: 'currency',
    name: 'Currency apps',
    category: '20 currency converters',
    route: '/apps/currency/',
    hidden: true,
    hasPolicies: false,
  },
];

export function getAppPage(pathname: string) {
  const path = pathname.replace(/\/$/, '');
  return appPages.find(
    (app) =>
      path === app.route.slice(0, -1) ||
      (app.hasPolicies &&
        ['support', 'privacy'].some((section) => path === `${app.route}${section}`)),
  );
}
